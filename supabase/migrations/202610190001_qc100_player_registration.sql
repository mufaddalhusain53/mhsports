create table if not exists public.qc100_player_registrations (
  id bigint generated by default as identity primary key,
  first_name text not null check (char_length(first_name) between 1 and 100),
  last_name text not null check (char_length(last_name) between 1 and 100),
  phone_number text not null check (phone_number ~ '^\+91[0-9]{10}$'),
  age integer not null check (age between 1 and 100),
  its_id text not null check (its_id ~ '^[0-9]{8}$'),
  season1_team text not null check (
    season1_team in (
      'Ezzi United',
      'Multiplize highlanders',
      'Mavericks',
      'Strikers',
      'Not played'
    )
  ),
  role text not null check (
    role in ('Batsman', 'Bowler', 'Wicket Keeper', 'All Rounder')
  ),
  batting_style text not null check (
    batting_style in (
      'RH Top Order',
      'RH Middle Order',
      'RH Finisher',
      'RH Lower Order',
      'LH Top Order',
      'LH Middle Order',
      'LH Finisher',
      'LH Lower Order'
    )
  ),
  bowling_style text not null check (
    bowling_style in (
      'Right-Arm Medium',
      'Left-Arm Medium',
      'Off Spin',
      'Leg break',
      'Orthodox',
      'Chinaman'
    )
  ),
  photo_path text not null,
  photo_url text not null,
  consent_accepted boolean not null check (consent_accepted),
  consented_at timestamptz not null,
  auction_available boolean not null default true,
  created_at timestamptz not null default now()
);

alter table public.qc100_player_registrations
  add column if not exists auction_available boolean not null default true;

alter table public.qc100_player_registrations enable row level security;
revoke all on public.qc100_player_registrations from anon, authenticated;
grant all privileges on public.qc100_player_registrations to service_role;
grant usage, select on sequence public.qc100_player_registrations_id_seq to service_role;

drop index if exists public.qc100_player_registrations_phone_number_unique;
drop index if exists public.qc100_player_registrations_its_id_unique;
create unique index if not exists qc100_player_registrations_its_id_phone_number_unique
  on public.qc100_player_registrations (its_id, phone_number);

