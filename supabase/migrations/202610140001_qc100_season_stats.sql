create table if not exists public.qc100_season_stats_raw (
  id bigint generated by default as identity primary key,
  season integer not null check (season between 1 and 2),
  category text not null check (category in ('batting','bowling','fielding','mvp')),
  file_name text not null,
  csv_content text not null,
  updated_at timestamptz not null default now(),
  constraint qc100_season_category_unique unique (season, category)
);
alter table public.qc100_season_stats_raw enable row level security;
-- Access is performed server-side through the Supabase service-role client.
